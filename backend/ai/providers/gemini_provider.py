import json
import logging
import urllib.error
import urllib.request
from typing import Any, Dict, List, Optional
from .base import BaseAIProvider

logger = logging.getLogger(__name__)


class GeminiProvider(BaseAIProvider):
    """
    Production-ready Google Gemini API adapter using official REST endpoint
    with standard library urllib (zero external pip dependencies).
    """

    def __init__(
        self,
        api_key: str,
        model: str = "gemini-1.5-flash",
        timeout_seconds: int = 15,
    ):
        self.api_key = api_key
        self.model = model
        self.timeout_seconds = timeout_seconds

    def generate_chat_response(
        self,
        messages: List[Dict[str, str]],
        system_instruction: str,
        tools: Optional[List[Dict[str, Any]]] = None,
        tool_results: Optional[List[Dict[str, Any]]] = None,
        max_tokens: int = 800,
        temperature: float = 0.2,
    ) -> Dict[str, Any]:
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY is not configured.")

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        contents = []
        for msg in messages:
            role = "user" if msg.get("role") == "user" else "model"
            contents.append({
                "role": role,
                "parts": [{"text": msg.get("content", "")}],
            })

        # If previous turn had tool calls and now has tool results
        if tool_results:
            parts = []
            for tr in tool_results:
                parts.append({
                    "functionResponse": {
                        "name": tr.get("name"),
                        "response": {"output": tr.get("result")},
                    }
                })
            contents.append({"role": "function", "parts": parts})

        payload: Dict[str, Any] = {
            "contents": contents,
            "systemInstruction": {
                "parts": [{"text": system_instruction}]
            },
            "generationConfig": {
                "temperature": temperature,
                "maxOutputTokens": max_tokens,
            },
        }

        # Format function declarations if tools provided
        if tools:
            func_decls = []
            for t in tools:
                func_decls.append({
                    "name": t.get("name"),
                    "description": t.get("description", ""),
                    "parameters": t.get("parameters", {"type": "OBJECT", "properties": {}}),
                })
            payload["tools"] = [{"functionDeclarations": func_decls}]

        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data_bytes,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self.timeout_seconds) as resp:
                raw_body = resp.read().decode("utf-8")
                resp_json = json.loads(raw_body)
        except urllib.error.HTTPError as e:
            err_body = e.read().decode("utf-8", errors="replace")
            logger.error("Gemini API HTTP Error %s: %s", e.code, err_body)
            raise RuntimeError(f"Gemini API returned status {e.code}: {err_body}")
        except Exception as e:
            logger.error("Gemini API connection error: %s", str(e))
            raise RuntimeError(f"Failed to communicate with Gemini API: {str(e)}")

        candidates = resp_json.get("candidates", [])
        if not candidates:
            return {
                "content": "No response was generated by the model.",
                "tool_calls": [],
                "usage": {"prompt_tokens": 0, "completion_tokens": 0},
                "model": self.model,
            }

        candidate = candidates[0]
        content_parts = candidate.get("content", {}).get("parts", [])
        text_parts = []
        tool_calls = []

        for p in content_parts:
            if "text" in p:
                text_parts.append(p["text"])
            if "functionCall" in p:
                fc = p["functionCall"]
                tool_calls.append({
                    "name": fc.get("name"),
                    "arguments": fc.get("args", {}),
                })

        usage_meta = resp_json.get("usageMetadata", {})
        usage = {
            "prompt_tokens": usage_meta.get("promptTokenCount", 0),
            "completion_tokens": usage_meta.get("candidatesTokenCount", 0),
        }

        return {
            "content": "".join(text_parts),
            "tool_calls": tool_calls,
            "usage": usage,
            "model": self.model,
        }
